import { expect, test } from "@playwright/test"
import { SETUP_TOKEN } from "../playwright.config"

const admin = { name: "Евгений", email: "owner@e2e.test", password: "owner-password-1" }

test("existing mortgage: preview, mobile schedule, calendar payment and atomic confirmation", async ({ page }) => {
  await page.goto("/")
  if (page.url().includes("/setup")) {
    await page.getByLabel("Токен настройки").fill(SETUP_TOKEN)
    await page.getByLabel("Имя").fill(admin.name)
    await page.getByLabel("E-mail").fill(admin.email)
    await page.getByLabel("Пароль", { exact: true }).fill(admin.password)
    await page.getByLabel("Повторите пароль").fill(admin.password)
    await page.getByRole("button", { name: "Создать администратора" }).click()
    await expect(page).toHaveURL(/\/onboarding/)
  } else {
    await page.goto("/login")
    await page.getByLabel("E-mail").fill(admin.email)
    await page.getByLabel("Пароль", { exact: true }).fill(admin.password)
    await page.getByRole("button", { name: "Войти", exact: true }).click()
    await expect(page).toHaveURL(/\/dashboard|\/onboarding/)
  }
  await page.goto("/onboarding?new=1")
  await page.getByLabel("Название").fill("Ипотека E2E")
  await page.getByRole("button", { name: "Создать", exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard/)
  await page.goto("/loans/new")
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole("radio", { name: "Уже выплачиваю", exact: true }).click()
  await page.getByLabel("Название", { exact: true }).fill("Семейная ипотека")
  await page.getByLabel("Банк", { exact: true }).fill("Банк Пример")
  await page.getByLabel("Текущий остаток долга").fill("100000")
  await page.getByLabel("Исходная сумма (необязательно)").fill("200000")
  await page.getByLabel("Ставка, % годовых").fill("12")
  await page.getByLabel("Осталось месяцев").fill("12")
  await page.getByLabel("Остаток на дату").click()
  await page.getByRole("button", { name: "Вчера", exact: true }).last().click()
  await page.getByLabel("Дата начала кредита").click()
  await page.getByRole("button", { name: "Вчера", exact: true }).last().click()
  await page.getByLabel("Дата следующего платежа").click()
  await page.getByRole("button", { name: "Сегодня", exact: true }).last().click()
  await page.getByLabel("Начисление процентов").click()
  await page.getByRole("option", { name: "Ежемесячно (r/12)", exact: true }).click()
  const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await noOverflow()
  await page.getByRole("button", { name: "Предпросмотр графика", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Предпросмотр графика" })).toBeVisible()
  await expect(page.getByText(/8\s884,88/).first()).toBeVisible()
  await noOverflow()
  await page.screenshot({ path: test.info().outputPath("loan-preview-375.png"), fullPage: true })
  await page.getByRole("button", { name: "Сохранить кредит", exact: true }).click()
  await expect(page).toHaveURL(/\/loans\/[a-f0-9-]+$/)
  const loanUrl = page.url()
  await expect(page.getByRole("heading", { name: "График погашения", exact: true })).toBeVisible()
  await expect(page.getByText("100 000 ₽", { exact: true }).first()).toBeVisible()
  await page.getByText("Кредит создан", { exact: true }).waitFor({ state: "hidden" })
  await page.getByLabel("Сумма досрочки").fill("10000")
  await expect(page.getByText("Экономия процентов", { exact: true }).first()).toBeVisible()
  await noOverflow()
  await page.mouse.move(0, 0)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: test.info().outputPath("loan-detail-375.png"), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: test.info().outputPath("loan-detail-desktop.png"), fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto("/calendar")
  await noOverflow()
  await page.getByRole("radio", { name: "Список", exact: true }).click()
  const item = page.getByRole("listitem").filter({ hasText: "Платёж по кредиту: Семейная ипотека" })
  await expect(item).toHaveCount(1)
  await page.screenshot({ path: test.info().outputPath("loan-calendar-375.png"), fullPage: true })
  await item.getByRole("button", { name: /Подтвердить/ }).click()
  const dialog = page.getByRole("dialog")
  await expect(dialog.getByRole("heading", { name: "Подтвердить платёж по кредиту" })).toBeVisible()
  await expect(dialog).toContainText(/7\s884,88/)
  await expect(dialog).toContainText(/1\s000/)
  await expect(dialog).toHaveCSS("opacity", "1")
  await noOverflow()
  await page.screenshot({ path: test.info().outputPath("loan-confirm-375.png"), fullPage: true })
  await dialog.getByRole("button", { name: "Подтвердить", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.goto(loanUrl)
  await expect(page.getByText("92 115,12 ₽", { exact: true }).first()).toBeVisible()
  await expect(page.getByText("Оплачен", { exact: true }).filter({ visible: true }).first()).toBeVisible()
  await noOverflow()
  await page.goto("/accounts")
  await expect(page.getByRole("listitem").filter({ hasText: "Основной счёт" }).getByText("−8 884,88 ₽", { exact: true })).toBeVisible()
  await expect(page.getByRole("listitem").filter({ hasText: "Семейная ипотека" }).getByText("−92 115,12 ₽", { exact: true })).toBeVisible()
  await noOverflow()
  await page.goto("/loans")
  await expect(page.getByRole("link", { name: "Семейная ипотека", exact: true })).toBeVisible()
  await noOverflow()
})
